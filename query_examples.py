"""Run three example queries and save their raw retrieval results to results.json."""
import json
import urllib.error
import urllib.request

API_URL = "http://127.0.0.1:8000/query"
QUERIES = [
    "What steps does the PDF ingestion pipeline perform?",
    "What should the retrieval endpoint return?",
    "What are the assessment deliverables and evaluation criteria?",
]


def post_query(query, top_k=3):
    payload = json.dumps({"query": query, "top_k": top_k}).encode("utf-8")
    request = urllib.request.Request(
        API_URL, data=payload,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=120) as response:
            return json.loads(response.read().decode("utf-8"))
    except urllib.error.URLError as exc:
        raise SystemExit(
            f"Could not reach {API_URL}. Start the server first. Details: {exc}"
        )


def main():
    output = {
        "note": "Generated by query_examples.py against the currently ingested PDF.",
        "queries": []
    }
    for query in QUERIES:
        output["queries"].append({
            "query": query,
            "results": post_query(query, top_k=3)
        })
    with open("results.json", "w", encoding="utf-8") as file:
        json.dump(output, file, indent=2, ensure_ascii=False)
    print("Wrote results.json")


if __name__ == "__main__":
    main()
